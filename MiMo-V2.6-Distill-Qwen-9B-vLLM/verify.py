"""Verify saved experiment evidence. This command does not run online accuracy."""
import argparse,hashlib,json,math,sys
from pathlib import Path

ROOT=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'scripts'))
from check_cell import check
from gsm8k_score import summarize as gsm8k_summary
from prediction_io import read_predictions
from evidence_codec import read_text

def read(p):return json.loads(read_text(p))
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--selfcheck',action='store_true');parser.parse_args()
    release=read(ROOT/'results/release.json')
    screen=ROOT/'results'/release['screen'];job=ROOT/'results'/release['formal']
    assert read(screen/'state.json')['stage']=='completed'
    assert read(job/'state.json')['stage']=='completed'
    summary=read(job/'summary.json')
    assert summary['complete'] and summary['counted_requests']==608 and summary['counted_output_tokens']==622592
    assert (ROOT/'env.log').is_file() and (ROOT/'server.log').is_file() and (ROOT/'smoke.log').is_file()
    assert (ROOT/'results/preflight.exit').read_text().strip()=='0'
    weights=read(ROOT/'results'/release['preflight']/'weights-check.json')
    assert weights['passed'] and weights['revision']=='2367e865d009c13ac81713a2878291d33ab28177'
    expected={x['Name']:x for x in read(ROOT/'sources/weight-files.json')['Data']['Files'] if x['Name'] not in ['README.md','.gitattributes','configuration.json']}
    assert len(expected)==len(weights['files'])==15
    for f in weights['files']:
        assert f['sha256']==expected[f['path']]['Sha256'] and f['bytes']==expected[f['path']]['Size']
    assert read(ROOT/'results/client-compat-v2/check.json')['passed']
    entry=ROOT/'results/entry-preparation-check'
    assert read(entry/'weights-check.json')['passed'] and len(read(entry/'weights-check.json')['files'])==15
    assert read(entry/'environment.json')['image_environment_fallback'] is True
    assert (ROOT/'results/entry-preparation.exit').read_text().strip()=='0'
    for target in [ROOT/'results/initial',screen/'eager',screen/'graph',job]:
        summary=read(target/'functional/summary.json')
        assert summary['passed'] and summary['successful']==summary['total']==17
    for mode in ['eager','graph']:
        target=screen/mode/'short';summary=read(target/'summary.json')
        assert summary['passed'] and summary['measured_requests']==16 and summary['client_warmup_requests']==5
        rows=[json.loads(x) for x in read_text(target/'result.jsonl').splitlines()]
        assert len(rows)==2 and {r['max_concurrency'] for r in rows}=={1,4}
        for r in rows:
            assert r['completed']==8 and r['total_output_tokens']==1024
            assert r['input_lens']==[512]*8 and r['output_lens']==[128]*8 and not any(r['errors'])
            assert all(t.strip() for t in r['generated_texts'])
            assert math.isclose(r['output_throughput'],1024/r['duration'],rel_tol=1e-6)
    context=read(job/'context-probe.json')
    assert context['raw_response']['usage']['prompt_tokens']==len(context['request']['prompt'])==16384
    assert context['raw_response']['usage']['completion_tokens']==32
    count=0
    for repeat in [1,2]:
        source=job/f'round{repeat}.jsonl'
        assert source.read_bytes()==(ROOT/'bench/saved-release'/source.name).read_bytes()
        rows=[json.loads(x) for x in read_text(source).splitlines()]
        assert len(rows)==6 and {(r['random_input_len'],r['max_concurrency']) for r in rows}=={(n,c) for n in [4096,16384] for c in [1,8,64]}
        for row in rows:
            length=row['random_input_len'];c=row['max_concurrency']
            raw=job/f'round{repeat}_{length}_1024_c{c}-raw'
            count+=check(row,raw,length,c)
    assert count==608
    assert 'OWNED_SERVICE_STOPPED' in (job/'stop.log').read_text(encoding='utf-8')
    # Live bench output can be regenerated by the documented commands. Keep the
    # immutable release independently checked, then validate a fresh run if any.
    current=read(ROOT/'results/formal-current.json')
    live=ROOT/'results'/Path(current['path']).name
    assert live.is_dir(), 'Current matrix evidence missing'
    assert read(live/'state.json')['stage']=='completed', 'Current matrix incomplete or failed'
    latest_count=0
    for repeat in [1,2]:
        source=live/f'round{repeat}.jsonl'
        assert source.read_bytes()==(ROOT/'bench'/source.name).read_bytes()
        rows=[json.loads(x) for x in read_text(source).splitlines()]
        assert len(rows)==6 and {(r['random_input_len'],r['max_concurrency']) for r in rows}=={(n,c) for n in [4096,16384] for c in [1,8,64]}
        for row in rows:
            length=row['random_input_len'];c=row['max_concurrency']
            latest_count+=check(row,live/f'round{repeat}_{length}_1024_c{c}-raw',length,c)
    assert latest_count==608
    live_summary=read(live/'summary.json')
    assert live_summary['complete'] and live_summary['counted_requests']==608 and live_summary['counted_output_tokens']==622592
    assert (ROOT/'bench/summary.json').read_bytes()==(live/'summary.json').read_bytes()
    assert read(live/'functional/summary.json')['successful']==17
    assert read(live/'context-probe.json')['raw_response']['usage']['prompt_tokens']==16384
    assert 'OWNED_SERVICE_STOPPED' in (live/'stop.log').read_text(encoding='utf-8')
    accuracy=ROOT/'results'/release['accuracy']
    assert read(accuracy/'state.json')['stage']=='completed'
    assert read(accuracy/'functional/summary.json')['successful']==17
    rows=read_predictions(accuracy/'gsm8k');scored=gsm8k_summary(rows)
    assert scored==read(accuracy/'gsm8k/summary.json') and scored['technical_checks_passed']
    rescored=read(accuracy/'gsm8k/rescore.json')
    assert rescored['passed'] and rescored['matched_rows']==200 and rescored['ground_truth_and_request_hashes_checked']
    assert rescored['summary']==scored
    paired=read(accuracy/'gsm8k/sglang-comparison.json')
    assert paired['same_prompt_hashes']==paired['same_ground_truth']==200 and paired['sglang_correct']==179
    assert paired['vllm_correct']==scored['correct']
    old={r['index']:r for r in read(ROOT/'baselines/sglang-gsm8k-200.json')['rows']}
    new={r['index']:r for r in rows}
    assert len(paired['rows'])==200 and {r['index'] for r in paired['rows']}==set(range(200))
    for r in paired['rows']:
        before=old[r['index']];after=new[r['index']]
        assert r['input_sha256']==before['input_sha256'] and r['request_sha256']==after['request_sha256']
        assert r['sglang_correct']==before['correct'] and r['vllm_correct']==after['correct']
    protocol=read(accuracy/'gsm8k/protocol.json')
    assert protocol['dataset']['source_sha256']=='ee7b8da9e381df27b9e3f7758a159ab2bdaa4dbaa910546cbbc47e0cb44e4f59'
    assert protocol['dataset']['prepared_sha256']=='03bd22060d201b82f3545a56dc89a01d300a5406d79e1d51529fdedceb698546' and protocol['dataset']['sglang_sample_byte_identical']
    assert protocol['few_shot']==0 and protocol['max_tokens']==4096 and protocol['temperature']==0 and protocol['enable_thinking'] is True
    assert 'OWNED_SERVICE_STOPPED' in (accuracy/'stop.log').read_text(encoding='utf-8')
    accuracy_current=ROOT/'results'/Path(read(ROOT/'results/accuracy-current.json')['path']).name
    assert read(accuracy_current/'state.json')['stage']=='completed'
    current_score=gsm8k_summary(read_predictions(accuracy_current/'gsm8k'))
    assert current_score==read(accuracy_current/'gsm8k/summary.json') and current_score['technical_checks_passed']
    assert read(accuracy_current/'gsm8k/rescore.json')['summary']==current_score
    assert 'OWNED_SERVICE_STOPPED' in (accuracy_current/'stop.log').read_text(encoding='utf-8')
    manifest=read(ROOT/'submission-manifest.json')
    cpu=read(ROOT/'results/delivery-cpu-checks.json')
    assert cpu['saved_evidence_exit']==cpu['mutable_live_log_exit']==cpu['model_requests_sent']==0
    assert cpu['missing_release_exit']!=0 and cpu['corrupt_compressed_evidence_exit']!=0
    if (ROOT/'sources/evidence-view-map.json').exists():
        view=read(ROOT/'sources/evidence-view-validation.json')
        assert view['passed'] and view['all_original_json_values_preserved']
        assert view['files_checked']==len(read(ROOT/'sources/evidence-view-map.json'))
    for item in manifest['files']:
        p=ROOT/item['path'];assert p.resolve().is_relative_to(ROOT)
        assert p.stat().st_size==item['bytes'],item['path']
        assert hashlib.sha256(p.read_bytes()).hexdigest()==item['sha256'],item['path']
    result={'saved_evidence_checks_passed':True,'functional_per_service':17,'counted_performance_requests':count,
            'counted_output_tokens':count*1024,'online_accuracy_executed':True,'accuracy_required':True,
            'functional_services':5,'gsm8k':scored,'latest_gsm8k':current_score,
            'latest_matrix_checks_passed':True,'latest_matrix_requests':latest_count,
            'minimum_accuracy_reference':'Qwen/Qwen3.5-9B','official_accuracy_pass':None,'official_acceptance':None,
            'independent_service_full_reproduction':None}
    (ROOT/'verify_result.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps(result))

if __name__=='__main__':
    try:main()
    except Exception as e:
        (ROOT/'verify_result.json').write_text(json.dumps({'saved_evidence_checks_passed':False,'error':repr(e),'official_acceptance':None},indent=2)+'\n',encoding='utf-8',newline='\n')
        raise
